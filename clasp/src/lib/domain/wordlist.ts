function selectWord(words: readonly string[]): string {
  return words[Math.floor(Math.random() * words.length)];
}

function capitalize(word: string): string {
  return word[0].toUpperCase() + word.slice(1);
}

export function generatePascalSecret(): string {
  return [
    selectWord(ADJECTIVES),
    selectWord(ADJECTIVES),
    selectWord(ADJECTIVES),
    selectWord(NOUNS),
  ]
    .map(capitalize)
    .join("");
}
